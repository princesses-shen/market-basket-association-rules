def infer_tier(company):
    """根据公司名推断档次"""
    if not company:
        return "中小-初创"
    company = company.strip()
    for name in HEAD_BIG:
        if name in company:
            return "头部大厂"
    for name in MID_BIG:
        if name in company:
            return "中大型企业"
    if any(kw in company for kw in ["有限公司","股份","集团","科技有限"]):
        if any(kw in company for kw in ["投资","管理","咨询","服务","商贸","贸易"]):
            return "成长型企业"
        return "成长型企业"
    return "中小-初创"

